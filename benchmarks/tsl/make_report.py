"""Aggregate TSL-baseline and Module C runs into docs/results_benchmark.md + a figure.

    python benchmarks/tsl/make_report.py [--zip ~/Downloads/tsl_runs.zip ...]

Every number is the mean ± std over the seeds that finished; the seed count is printed in each
cell. Missing cells are shown as "not run" — nothing is filled in from papers.
"""

from __future__ import annotations

import argparse
import json
import zipfile
from collections import defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "outputs" / "benchmark"
DOCS = ROOT / "docs"
DATASETS = ("ETTh1", "ETTm1", "weather", "traffic")
HORIZONS = (96, 192, 336, 720)
METHODS = ("Transformer", "iTransformer", "PatchTST",
           "Module C (quantum fidelity)", "Module C (cosine)", "Module C (learned metric)")
MC = {"quantum_fidelity": METHODS[3], "cosine": METHODS[4], "learned_metric": METHODS[5]}
SERIES = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#6250d6"]
SURFACE, INK, INK2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
plt.rcParams.update({
    "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
    "axes.edgecolor": GRID, "axes.labelcolor": INK2, "xtick.color": INK2, "ytick.color": INK2,
    "text.color": INK, "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.8,
    "axes.spines.top": False, "axes.spines.right": False, "font.size": 10, "lines.linewidth": 2,
})


def collect() -> dict:
    """{(dataset, horizon, method): {"mse": [...], "mae": [...], "seeds": [...]}}"""
    cells = defaultdict(lambda: {"mse": [], "mae": [], "seeds": []})
    for p in sorted((OUT / "tsl" / "runs").glob("*.json")):
        r = json.loads(p.read_text())
        if r.get("status") != "OK" or r.get("epochs_override"):
            continue
        c = cells[(r["dataset"], r["pred_len"], r["model"])]
        c["mse"].append(r["mse"]); c["mae"].append(r["mae"]); c["seeds"].append(r["seed"])
    for p in sorted((OUT / "module_c").glob("*.json")):
        r = json.loads(p.read_text())
        if r.get("status") != "OK" or r.get("quick"):
            continue
        for key, method in MC.items():
            if key in r["results"]:
                c = cells[(r["dataset"], r["pred_len"], method)]
                c["mse"].append(r["results"][key]["mse"]); c["mae"].append(r["results"][key]["mae"])
                c["seeds"].append(r["seed"])
                c.setdefault("stride", r.get("memory_stride", 1))
    return cells


def fmt(v: list[float]) -> str:
    return f"{np.mean(v):.3f} ± {np.std(v):.3f}" if len(v) > 1 else f"{v[0]:.3f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--zip", nargs="*", type=Path, default=[], help="Colab result zips to merge first")
    a = ap.parse_args()
    for z in a.zip:
        with zipfile.ZipFile(z) as f:
            f.extractall(ROOT)
        print(f"merged {z}")
    cells = collect()
    lines = ["# Benchmark — Module C vs Transformer / iTransformer / PatchTST", "",
             ("Generated by `benchmarks/tsl/make_report.py`. Time-Series-Library protocol "
              "(`docs/benchmark_protocol.md`): multivariate `M`, input 96, horizons 96/192/336/720, "
              "TSL splits and train-only scaling. Module C reads the same windows from TSL's own data "
              "loaders (`qss.data.tsl_adapter`). Baseline hyper-parameters are TSL's official "
              "`scripts/long_term_forecast` settings. MSE / MAE on normalized values over all variables. "
              "Each cell: mean ± std over the finished seeds (of 2021–2025), `n` = number of seeds. "
              "Lower is better; the best mean per row is bold."), ""]
    for d in DATASETS:
        if not any(k[0] == d for k in cells):
            lines += [f"## {d}", "", "not run", ""]
            continue
        lines += [f"## {d}", "", "| horizon | metric | " + " | ".join(METHODS) + " |",
                  "|---|---|" + "---|" * len(METHODS)]
        for h in HORIZONS:
            for metric in ("mse", "mae"):
                vals = {m: cells[(d, h, m)][metric] for m in METHODS if cells.get((d, h, m), {}).get(metric)}
                best = min(vals, key=lambda m: np.mean(vals[m])) if vals else None
                row = []
                for m in METHODS:
                    if m not in vals:
                        row.append("not run")
                        continue
                    s = f"{fmt(vals[m])} (n={len(vals[m])})"
                    row.append(f"**{s}**" if m == best else s)
                lines.append(f"| {h} | {metric.upper()} | " + " | ".join(row) + " |")
        strides = {cells[k].get("stride") for k in cells if k[0] == d and k[2].startswith("Module C")}
        if strides - {1, None}:
            lines.append(f"\nModule C memory bank on {d} keeps every {max(strides - {None})}-th training window.")
        lines.append("")
    # quantum vs classical re-ranking inside Module C (paired by seed)
    lines += ["## Module C: quantum fidelity vs classical re-ranking", "",
              "Paired by seed: Δ = MSE(quantum) − MSE(cosine). Negative means the quantum re-ranker helps.", "",
              "| dataset | horizon | n | Δ MSE mean | Δ MSE std | quantum better in |", "|---|---|---|---|---|---|"]
    for d in DATASETS:
        for h in HORIZONS:
            q, c = cells.get((d, h, MC["quantum_fidelity"])), cells.get((d, h, MC["cosine"]))
            if not q or not c:
                continue
            qd, cd = dict(zip(q["seeds"], q["mse"])), dict(zip(c["seeds"], c["mse"]))
            diff = np.array([qd[s] - cd[s] for s in qd if s in cd])
            lines.append(f"| {d} | {h} | {len(diff)} | {diff.mean():+.4f} | {diff.std():.4f} | "
                         f"{int((diff < 0).sum())}/{len(diff)} seeds |")
    lines.append("")
    # figure
    present = [d for d in DATASETS if any(k[0] == d for k in cells)]
    if present:
        fig, axes = plt.subplots(1, len(present), figsize=(4.2 * len(present), 3.8), squeeze=False)
        for ax, d in zip(axes[0], present):
            for i, m in enumerate(METHODS[:4]):
                hs = [h for h in HORIZONS if cells.get((d, h, m), {}).get("mse")]
                if not hs:
                    continue
                mu = [np.mean(cells[(d, h, m)]["mse"]) for h in hs]
                sd = [np.std(cells[(d, h, m)]["mse"]) for h in hs]
                ax.errorbar(hs, mu, yerr=sd, color=SERIES[i], marker="o", ms=5, capsize=3, label=m)
            ax.set_xticks(HORIZONS)
            ax.set_xlabel("horizon")
            ax.set_title(d, loc="left")
        axes[0][0].set_ylabel("test MSE (normalized)")
        axes[0][-1].legend(frameon=False, fontsize=8)
        fig.tight_layout()
        (DOCS / "figures").mkdir(parents=True, exist_ok=True)
        fig.savefig(DOCS / "figures" / "benchmark_mse.png", dpi=180)
        plt.close(fig)
        lines += ["![benchmark](figures/benchmark_mse.png)", ""]
    (DOCS / "results_benchmark.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
